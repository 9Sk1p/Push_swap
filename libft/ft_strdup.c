#include "libft.h"

char	*ft_strdup(const char *src)
{
	size_t	i;
	char	*dst;

	i = 0;
	dst = malloc((sizeof(char)) * (ft_strlen(src) + 1));
	if (dst == NULL)
		return (NULL);
	while (src[i])
	{
		dst[i] = src[i];
		i++;
	}
	dst[i] = '\0';
	return (dst);
}
